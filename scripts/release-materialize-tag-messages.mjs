#!/usr/bin/env node
// Fetch the release tag set, check each annotation's subject and attribution
// footer, and write the message bytes to MESSAGE_DIR as <tag with / as __>.txt
// for the post-tag guards. Used by the tag-triggered workflows.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const version = readFileSync("VERSION", "utf8").trim();
const releaseTag = process.env.RELEASE_TAG;
const messageDir = process.env.MESSAGE_DIR;
if (!messageDir) throw new Error("MESSAGE_DIR is required");
if (releaseTag !== `v${version}`) {
  throw new Error(`release tag ${releaseTag} does not match VERSION ${version}`);
}

// Same set as scripts/release-guard-tag-version.sh: the canonical tag, the Go
// binding tag when the plan publishes it, and the recurrence module tag when
// the module is in the tree.
const plan = JSON.parse(readFileSync(`docs/releases/v${version}.json`, "utf8"));
const expectedSubjects = new Map([[releaseTag, `Release ${version}`]]);
if (plan.surfaces.go.disposition === "publish") {
  expectedSubjects.set(`bindings/go/sysprims/${releaseTag}`, `bindings/go/sysprims/${releaseTag}`);
}
if (existsSync("go/recurrence/go.mod")) {
  expectedSubjects.set(`go/recurrence/${releaseTag}`, `go/recurrence/${releaseTag}`);
}
const tags = [...expectedSubjects.keys()];

execFileSync(
  "git",
  ["fetch", "--no-tags", "origin", ...tags.map((tag) => `refs/tags/${tag}:refs/tags/${tag}`)],
  { stdio: "inherit" },
);

const footer = new RegExp(
  "(?:^|\\n)Generated by .+ via .+ under supervision of @3leapsdave\\n\\n" +
    "Co-Authored-By: .+ <noreply@3leaps\\.net>\\n" +
    "Role: [a-z][a-z0-9-]*\\n" +
    "Committer-of-Record: @3leapsdave\\s*$",
);

for (const tag of tags) {
  const object = execFileSync("git", ["cat-file", "tag", `refs/tags/${tag}`]);
  const separator = object.indexOf(Buffer.from("\n\n"));
  if (separator === -1) throw new Error(`annotated tag object is malformed for ${tag}`);
  const message = object.subarray(separator + 2);
  const text = message.toString("utf8");
  if (text.split("\n", 1)[0] !== expectedSubjects.get(tag)) {
    throw new Error(`unexpected annotation subject for ${tag}`);
  }
  if (!footer.test(text)) {
    throw new Error(`tag ${tag} does not contain the complete attribution footer`);
  }
  writeFileSync(join(messageDir, `${tag.replaceAll("/", "__")}.txt`), message);
}
console.log(`[ok] verified and materialized ${tags.length} tag message(s)`);
