#!/usr/bin/env node
// Fetch the release tag set, check each annotation's subject and attribution
// footer, and write the message bytes (OpenPGP armor removed) to MESSAGE_DIR as
// <tag with / as __>.txt for the post-tag guards. Used by the tag-triggered
// workflows. The tag set is decided by the release commit, never the checkout.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { annotationBody, releaseTagSet, resolveCommit } from "./release-tag-set.mjs";

const releaseTag = process.env.RELEASE_TAG;
const messageDir = process.env.MESSAGE_DIR;
if (!messageDir) throw new Error("MESSAGE_DIR is required");
if (!/^v\d+\.\d+\.\d+$/.test(releaseTag ?? "")) throw new Error("RELEASE_TAG must be a canonical vX.Y.Z tag");
const root = process.cwd();

execFileSync("git", ["fetch", "--no-tags", "origin", `refs/tags/${releaseTag}:refs/tags/${releaseTag}`], { stdio: "inherit" });
const commit = resolveCommit(root, `refs/tags/${releaseTag}`);
const { version, tags } = releaseTagSet(root, commit, releaseTag);
const companions = tags.filter((tag) => tag !== releaseTag);
if (companions.length > 0) {
  execFileSync(
    "git",
    ["fetch", "--no-tags", "origin", ...companions.map((tag) => `refs/tags/${tag}:refs/tags/${tag}`)],
    { stdio: "inherit" },
  );
}

const footer = new RegExp(
  "(?:^|\\n)Generated by .+ via .+ under supervision of @3leapsdave\\n\\n" +
    "Co-Authored-By: .+ <noreply@3leaps\\.net>\\n" +
    "Role: [a-z][a-z0-9-]*\\n" +
    "Committer-of-Record: @3leapsdave\\n$",
);

for (const tag of tags) {
  if (resolveCommit(root, `refs/tags/${tag}`) !== commit) throw new Error(`${tag} does not point at the release commit ${commit}`);
  const message = annotationBody(root, tag);
  const text = message.toString("utf8");
  const subject = tag === releaseTag ? `Release ${version}` : tag;
  if (text.split("\n", 1)[0] !== subject) throw new Error(`unexpected annotation subject for ${tag}`);
  if (!footer.test(text)) throw new Error(`tag ${tag} does not contain the complete attribution footer`);
  writeFileSync(join(messageDir, `${tag.replaceAll("/", "__")}.txt`), message);
}
console.log(`[ok] verified and materialized ${tags.length} tag message(s) at ${commit}`);
