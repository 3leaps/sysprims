const defaultRoot = resolve(scriptDir, "..");
// Every command except provenance works on a tagged release: it takes the tag
// from SYSPRIMS_RELEASE_TAG (never v<VERSION> of the checkout), refuses a bare
// RELEASE_TAG, and reads VERSION at the tag's commit. provenance runs before
// the tag exists and uses the checkout. scripts/release-make-guard.py reads this
// list; independent per-target controls check the behaviour.
export const TAG_READING_COMMANDS = ["downloaded", "checksummed", "require-checksummed", "signed", "uploaded", "remote", "publish", "verify-registries"];

// The release named by SYSPRIMS_RELEASE_TAG: its commit, and VERSION read
// there. Every later decision for the release is taken at that commit.
export function taggedRelease(root, env = process.env) {
  if (env.RELEASE_TAG !== undefined) fail("RELEASE_TAG is not accepted; set SYSPRIMS_RELEASE_TAG=vX.Y.Z");
  const tag = env.SYSPRIMS_RELEASE_TAG;
  if (!tag) fail("SYSPRIMS_RELEASE_TAG=vX.Y.Z is required");
  if (!/^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(tag)) fail("SYSPRIMS_RELEASE_TAG must be a canonical vX.Y.Z tag");
  const commit = resolveCommit(root, `refs/tags/${tag}`);
  const version = run(root, "git", ["cat-file", "blob", `${commit}:VERSION`]).replace(/\n$/, "");
  if (`v${version}` !== tag) fail(`SYSPRIMS_RELEASE_TAG ${tag} does not match VERSION ${version} at its commit`);
  return { version, commit };
}

// Index entries marked skip-worktree or assume-unchanged hide working-tree
// changes from status checks; refuse them rather than reason about them.
export function refuseHiddenIndexEntries(root) {
  const flagged = run(root, "git", ["ls-files", "-v"]).split("\n").filter((line) => line && !line.startsWith("H "));
  if (flagged.length) fail(`index entries hide working-tree changes (skip-worktree or assume-unchanged):\n${flagged.slice(0, 5).join("\n")}`);
}
const footerPattern = /(?:^|\n)(?:(?:Generated by .+ via .+ under supervision of @3leapsdave\n\n)?Role: [a-z][a-z0-9-]*\nCo-[Aa]uthored-[Bb]y: .+ <noreply@3leaps\.net>|Generated by .+ via .+ under supervision of @3leapsdave\n\nCo-[Aa]uthored-[Bb]y: .+ <noreply@3leaps\.net>\nRole: [a-z][a-z0-9-]*)\nCommitter-of-Record: @3leapsdave\s*$/;

function fail(message) {
  throw new Error(message);
}

function run(root, command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    env: process.env,
    ...options,
  });
  if (result.error) fail(`cannot run ${command}: ${result.error.message}`);
  if (result.status !== 0) {
    const detail = `${result.stderr || ""}${result.stdout || ""}`.trim();
    fail(`${command} ${args.join(" ")} failed${detail ? `:\n${detail}` : ""}`);
  }
  return result.stdout;
}

function readVersion(root) {
  const value = readFileSync(join(root, "VERSION"), "utf8");
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?\n$/.test(value)) fail("VERSION is not canonical SemVer plus LF");
  return value.trim();
}

function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

export function expectedInventory(version) {
  const base = [
    "LICENSE-APACHE",
    "LICENSE-MIT",
    `release-notes-v${version}.md`,
    ...ANCHORS.map(([, name]) => name),
    `sbom-${version}.cdx.json`,
    `sysprims-${version}-darwin-amd64.tar.gz`,
    `sysprims-${version}-darwin-arm64.tar.gz`,
    `sysprims-${version}-linux-amd64-musl.tar.gz`,
    `sysprims-${version}-linux-amd64.tar.gz`,
    `sysprims-${version}-linux-arm64-musl.tar.gz`,
    `sysprims-${version}-linux-arm64.tar.gz`,
    `sysprims-${version}-windows-amd64.zip`,
    `sysprims-${version}-windows-arm64.zip`,
    `sysprims-ffi-${version}-libs.tar.gz`,
    "sysprims.h",
  ].sort();
  const checksummed = [...base, "SHA256SUMS", "SHA512SUMS"].sort();
  const signed = [
    ...checksummed,
    "SHA256SUMS.asc",
    "SHA256SUMS.minisig",
    "SHA512SUMS.asc",
    "SHA512SUMS.minisig",
    "sysprims-minisign.pub",
    "sysprims-release-signing-key.asc",
  ].sort();
  return { base, checksummed, signed };
}

function filesIn(directory) {
  if (!existsSync(directory)) fail(`release directory is missing: ${directory}`);
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort();
}

export function assertInventory(directory, expected, phase) {
  const actual = filesIn(directory);
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    const missing = expected.filter((name) => !actual.includes(name));
    const extra = actual.filter((name) => !expected.includes(name));
    fail(`${phase} inventory mismatch; missing=[${missing.join(", ")}], extra=[${extra.join(", ")}]`);
  }
}

function releaseMetadata(root, tag) {
  const fixture = process.env.SYSPRIMS_RELEASE_METADATA_FILE;
  if (fixture) return JSON.parse(readFileSync(fixture, "utf8"));
  return JSON.parse(run(root, "gh", ["release", "view", tag, "--json", "assets,isDraft,tagName,targetCommitish"]));
}

function assertDraft(metadata, tag) {
  if (metadata.tagName !== tag) fail(`release metadata tag is ${metadata.tagName}, expected ${tag}`);
  if (metadata.isDraft !== true) fail(`release ${tag} must still be a draft`);
}

function verifyAssetDigests(directory, assets, names) {
  const byName = new Map((assets ?? []).map((asset) => [asset.name, asset]));
  for (const name of names) {
    const asset = byName.get(name);
    if (!asset) fail(`GitHub release asset is missing: ${name}`);
    const digest = asset.digest?.replace(/^sha256:/, "");
    if (!/^[0-9a-f]{64}$/.test(digest ?? "")) fail(`GitHub release asset has no SHA-256 digest: ${name}`);
    if (digest !== sha256(join(directory, name))) fail(`GitHub digest mismatch for ${name}`);
  }
}

// Release assets taken from the tagged commit's blobs rather than built by CI:
// the notes and the fingerprint anchors. They are staged locally before the
// checksums, so they are covered by the signed manifests, and at every phase
// each must equal its blob at the tag's commit byte for byte.
export const ANCHORS = [
  ["keys/expected-fingerprints.txt", "expected-fingerprints.txt"],
  ["keys/expected-fingerprints.ndjson", "expected-fingerprints.ndjson"],
];
function taggedAssets(version) {
  return [[`docs/releases/v${version}.md`, `release-notes-v${version}.md`], ...ANCHORS];
}
const isTaggedAsset = (version) => (name) => taggedAssets(version).some(([, asset]) => asset === name);
// Names of the release assets taken from the tagged commit, not from CI.
export const TAGGED_ASSET_NAMES = (version) => taggedAssets(version).map(([, asset]) => asset);

export function verifyTaggedAssets(root, directory, version) {
  const commit = resolveCommit(root, `refs/tags/v${version}`);
  for (const [path, name] of taggedAssets(version)) {
    const entry = run(root, "git", ["ls-tree", commit, "--", path]).split(/\s/);
    if (!["100644", "100755"].includes(entry[0]) || entry[1] !== "blob") fail(`committed ${path} is required in the tagged commit`);
    const tagged = spawnSync("git", ["cat-file", "blob", `${commit}:${path}`], { cwd: root }).stdout;
    if (!tagged?.length) fail(`committed ${path} is empty in the tagged commit`);
    const file = join(directory, name);
    if (!existsSync(file) || lstatSync(file).isSymbolicLink() || !lstatSync(file).isFile()) fail(`${name} is missing or not a regular file`);
    if (!readFileSync(file).equals(tagged)) fail(`${name} does not match the immutable tag-tree blob ${path}`);
  }
}

function parseManifest(path, algorithm) {
  const lines = readFileSync(path, "utf8").trimEnd().split("\n");
  const entries = new Map();
  const length = algorithm === "sha256" ? 64 : 128;
  for (const line of lines) {
    const match = line.match(new RegExp(`^([0-9a-f]{${length}})  (.+)$`));
    if (!match || entries.has(match[2])) fail(`invalid or duplicate ${basename(path)} entry: ${line}`);
    entries.set(match[2].replace(/^\.\//, ""), match[1]);
  }
  return entries;
}

export function verifyChecksums(directory, base) {
  for (const [name, algorithm] of [["SHA256SUMS", "sha256"], ["SHA512SUMS", "sha512"]]) {
    const entries = parseManifest(join(directory, name), algorithm);
    if (JSON.stringify([...entries.keys()].sort()) !== JSON.stringify(base)) fail(`${name} does not cover the exact base payload inventory`);
    for (const file of base) {
      const actual = createHash(algorithm).update(readFileSync(join(directory, file))).digest("hex");
      if (entries.get(file) !== actual) fail(`${name} digest mismatch for ${file}`);
    }
  }
}

// The CI payload record written by release-fetch-ci-artifacts.sh beside the
// staging directory (never inside it, so it is never uploaded). Until the draft
// exists, the staged CI files are checked against it: same tag object and
// commit as the verified tag, and each file's bytes as fetched.
export function readFetchAnchor(root, directory, version) {
  const path = `${directory}.anchor`;
  if (!existsSync(path) || lstatSync(path).isSymbolicLink() || !lstatSync(path).isFile()) fail(`missing ${path}; stage the CI payload with make release-download`);
  const fields = new Map();
  const files = new Map();
  for (const line of readFileSync(path, "utf8").split("\n")) {
    if (!line) continue;
    const file = /^file=([0-9a-f]{64}) ([A-Za-z0-9][A-Za-z0-9._-]*)$/.exec(line);
    if (file) {
      if (files.has(file[2])) fail(`${path} lists ${file[2]} twice`);
      files.set(file[2], file[1]);
      continue;
    }
    const field = /^(tag|object|commit|run|attempt|artifact|digest)=(.+)$/.exec(line);
    if (!field || fields.has(field[1])) fail(`${path} is malformed`);
    fields.set(field[1], field[2]);
  }
  const tag = `v${version}`;
  if (fields.get("tag") !== tag) fail(`${path} is for ${fields.get("tag")}, expected ${tag}`);
  const object = resolveObject(root, `refs/tags/${tag}`);
  if (fields.get("object") !== object) fail(`${path} records tag object ${fields.get("object")}, local ${tag} is ${object}`);
  if (fields.get("commit") !== resolveCommit(root, `refs/tags/${tag}`)) fail(`${path} records a different commit than ${tag}`);
  return { fields, files };
}

function resolveObject(root, ref) {
  const object = run(root, "git", ["rev-parse", "--verify", "--quiet", ref]).trim();
  if (!/^[0-9a-f]{40}$/.test(object)) fail(`cannot resolve ${ref}`);
  return object;
}

// The CI-built files (everything but the tag-blob assets) must be exactly the
// fetched set and still hold the fetched bytes.
function verifyFetchedPayload(root, directory, version) {
  const { files } = readFetchAnchor(root, directory, version);
  const built = expectedInventory(version).base.filter((name) => !isTaggedAsset(version)(name));
  const recorded = [...files.keys()].sort();
  if (JSON.stringify(recorded) !== JSON.stringify(built)) fail(`fetched CI payload does not match the expected inventory; recorded=[${recorded.join(", ")}]`);
  for (const name of built) {
    if (sha256(join(directory, name)) !== files.get(name)) fail(`${name} differs from the fetched CI artifact`);
  }
}

function downloaded(root, directory, version) {
  const { base } = expectedInventory(version);
  assertInventory(directory, base, "downloaded");
  verifyTaggedAssets(root, directory, version);
  verifyFetchedPayload(root, directory, version);
}

function checksummed(root, directory, version) {
  const { base, checksummed: inventory } = expectedInventory(version);
  assertInventory(directory, inventory, "checksummed");
  verifyTaggedAssets(root, directory, version);
  verifyFetchedPayload(root, directory, version);
  verifyChecksums(directory, base);
}

function requireChecksummed(root, directory, version) {
  const { base, checksummed: required, signed: allowed } = expectedInventory(version);
  const actual = filesIn(directory);
  const missing = required.filter((name) => !actual.includes(name));
  const extra = actual.filter((name) => !allowed.includes(name));
  if (missing.length || extra.length) fail(`required checksummed state mismatch; missing=[${missing.join(", ")}], extra=[${extra.join(", ")}]`);
  verifyTaggedAssets(root, directory, version);
  verifyFetchedPayload(root, directory, version);
  verifyChecksums(directory, base);
}

function signed(root, directory, version) {
  const { base, signed: inventory } = expectedInventory(version);
  assertInventory(directory, inventory, "signed");
  verifyTaggedAssets(root, directory, version);
  verifyFetchedPayload(root, directory, version);
  verifyChecksums(directory, base);
  run(root, "bash", ["scripts/verify-signatures.sh", directory]);
  run(root, "bash", ["scripts/verify-public-keys.sh", directory]);
}

function uploaded(root, directory, version) {
  const tag = `v${version}`;
  const { signed: inventory } = expectedInventory(version);
  const metadata = releaseMetadata(root, tag);
  assertDraft(metadata, tag);
  const remoteNames = (metadata.assets ?? []).map((asset) => asset.name).sort();
  if (JSON.stringify(remoteNames) !== JSON.stringify(inventory)) fail("remote signed asset inventory is incomplete or contains extras");
  const fixtureDir = process.env.SYSPRIMS_REMOTE_ASSET_DIR;
  const temporary = fixtureDir ? null : mkdtempSync(join(tmpdir(), "sysprims-release-remote-"));
  const remoteDir = fixtureDir ?? temporary;
  try {
    if (!fixtureDir) run(root, "gh", ["release", "download", tag, "--dir", remoteDir]);
    assertInventory(remoteDir, inventory, "remote uploaded");
    verifyAssetDigests(remoteDir, metadata.assets, inventory);
    verifyTaggedAssets(root, remoteDir, version);
    verifyChecksums(remoteDir, expectedInventory(version).base);
    // The remote copy itself must carry valid signatures from the committed
    // pins and only public keys; local files are never the evidence here.
    run(root, "bash", ["scripts/verify-signatures.sh", remoteDir]);
    run(root, "bash", ["scripts/verify-public-keys.sh", remoteDir]);
    for (const name of inventory) {
      if (existsSync(join(directory, name)) && sha256(join(directory, name)) !== sha256(join(remoteDir, name))) fail(`remote/local mismatch for ${name}`);
    }
  } finally {
    if (temporary) rmSync(temporary, { recursive: true, force: true });
  }
}

// The required tag set comes from the shared resolver, which reads git blobs
// at the commit; the working tree is never consulted.
export function requiredTags(root = defaultRoot, commit = "HEAD", version = undefined) {
  return releaseTagSet(root, commit, version === undefined ? undefined : `v${version}`).tags;
}

function tagExists(root, tag) {
  return spawnSync("git", ["show-ref", "--verify", "--quiet", `refs/tags/${tag}`], { cwd: root }).status === 0;
}

function intendedTagMessage(tag) {
  const directory = process.env.SYSPRIMS_TAG_MESSAGE_DIR;
  if (!directory) fail("SYSPRIMS_TAG_MESSAGE_DIR was not supplied for tag-message verification");
  const path = join(directory, `${tag.replaceAll("/", "__")}.txt`);
  if (!existsSync(path)) fail(`proposed tag message is missing: ${path}`);
  return readFileSync(path, "utf8");
}

// The annotation's message bytes with any OpenPGP signature armor removed, so a
// signed tag compares equal to the reviewed unsigned message.
function tagMessage(root, tag) {
  if (tagExists(root, tag)) return annotationBody(root, tag).toString("utf8");
  return intendedTagMessage(tag);
}

function verifyIntendedTagMessages(root, tags) {
  const present = tags.filter((tag) => tagExists(root, tag));
  if (present.length === 0) return;
  if (present.length !== tags.length) fail("required local tag set is incomplete for tag-message verification");
  for (const tag of tags) {
    const actual = tagMessage(root, tag);
    const intended = intendedTagMessage(tag);
    if (actual !== intended) fail(`tag message does not match the intended bytes for ${tag}`);
  }
}

function verifyReceipt(root, version, commit, tags) {
  const receiptPath = process.env.SYSPRIMS_PROVENANCE_EXCEPTION_RECEIPT;
  const publicKey = process.env.SYSPRIMS_PROVENANCE_EXCEPTION_PUBKEY;
  if (!receiptPath || !publicKey) fail("complete attribution footer is missing and no signed exception receipt was supplied");
  const signaturePath = `${receiptPath}.minisig`;
  if (!existsSync(signaturePath)) fail("provenance exception receipt signature is missing");
  const args = existsSync(publicKey)
    ? ["-Vm", receiptPath, "-x", signaturePath, "-p", publicKey]
    : ["-Vm", receiptPath, "-x", signaturePath, "-P", publicKey];
  run(root, "minisign", args);
  const receipt = JSON.parse(readFileSync(receiptPath, "utf8"));
  if (receipt.schema !== "sysprims-release-provenance-exception/v1") fail("unknown provenance exception receipt schema");
  if (receipt.version !== version) fail("provenance exception receipt version mismatch");
  if (receipt.target_commit !== commit || !/^[0-9a-f]{40}$/.test(receipt.target_commit)) fail("provenance exception receipt target commit mismatch");
  const approvedMaintainers = (process.env.SYSPRIMS_PROVENANCE_EXCEPTION_MAINTAINERS ?? "@3leapsdave").split(",").map((value) => value.trim()).filter(Boolean);
  if (!approvedMaintainers.includes(receipt.authorizing_maintainer)) fail("receipt maintainer identity is not approved by verifier configuration");
  if (!/^\d{4}-\d{2}-\d{2}T/.test(receipt.decided_at ?? "")) fail("receipt decision timestamp is missing");
  if (typeof receipt.approval_reference !== "string" || !receipt.approval_reference) fail("receipt durable approval reference is missing");
  const bound = new Map((receipt.tags ?? []).map((entry) => [entry.name, entry.message_sha256]));
  if (JSON.stringify([...bound.keys()].sort()) !== JSON.stringify([...tags].sort())) fail("receipt required tag set mismatch");
  for (const tag of tags) {
    const message = tagMessage(root, tag);
    if (!footerPattern.test(message)) fail(`tag ${tag} does not contain the complete attribution footer`);
    const digest = createHash("sha256").update(message).digest("hex");
    if (bound.get(tag) !== digest) fail(`receipt tag-message hash mismatch for ${tag}`);
  }
}

// `commit` defaults to HEAD, for use before the tag exists; once it does, the
// caller passes the tag's commit.
export function provenance(root, version, commit = run(root, "git", ["rev-parse", "HEAD^{commit}"]).trim()) {
  const body = run(root, "git", ["log", "-1", "--format=%B", commit]);
  const tags = requiredTags(root, commit, version);
  if (footerPattern.test(body)) {
    verifyIntendedTagMessages(root, tags);
    return;
  }
  verifyReceipt(root, version, commit, tags);
}

// What must be on the registries for the release at `commit`, read from git
// blobs there: every crate in config/release/publishable-crates.txt, the Go
// binding (published or retained), and the recurrence module when present.
export function remoteRequirements(root, commit, version) {
  const set = releaseTagSet(root, commit, `v${version}`);
  const crates = run(root, "git", ["cat-file", "blob", `${set.commit}:config/release/publishable-crates.txt`]).split("\n").filter(Boolean);
  if (crates.length === 0) fail("publishable-crates.txt is empty");
  const plan = JSON.parse(run(root, "git", ["cat-file", "blob", `${set.commit}:docs/releases/v${version}.json`]));
  const go = plan.surfaces.go;
  const modules = [{
    path: "github.com/3leaps/sysprims/bindings/go/sysprims",
    version: go.disposition === "publish" ? version : go.retained_version,
    absentAt: go.disposition === "publish" ? null : version,
  }];
  if (set.recurrence) modules.push({ path: "github.com/3leaps/sysprims/go/recurrence", version, absentAt: null });
  return { crates, modules };
}

// lookup.crate(name, version) -> resolved version or null;
// lookup.goModule(path, version) -> resolved version or null;
// lookup.npm(url) -> registry metadata (throws when absent);
// lookup.npmResolves(url) -> whether the registry has it.
export function checkRemote(requirements, version, lookup) {
  for (const crate of requirements.crates) {
    if (lookup.crate(crate, version) !== version) fail(`crates.io did not resolve ${crate}@${version}`);
  }
  for (const module of requirements.modules) {
    if (!module.version) fail(`no version to resolve for ${module.path}`);
    if (lookup.goModule(module.path, module.version) !== `v${module.version}`) fail(`Go module ${module.path} did not resolve v${module.version}`);
    if (module.absentAt && lookup.goModule(module.path, module.absentAt) !== null) fail(`skipped Go module ${module.path} unexpectedly resolves at v${module.absentAt}`);
  }
}

function liveLookup(root) {
  return {
    crate(name, version) {
      const result = spawnSync("curl", ["-fsSL", `https://crates.io/api/v1/crates/${name}/${version}`], { cwd: root, encoding: "utf8" });
      if (result.status !== 0) return null;
      return JSON.parse(result.stdout).version?.num ?? null;
    },
    goModule(path, version) {
      const result = spawnSync("go", ["list", "-m", "-json", `${path}@v${version}`], { cwd: root, encoding: "utf8" });
      if (result.status !== 0) return null;
      return JSON.parse(result.stdout).Version ?? null;
    },
    npm(url) {
      return JSON.parse(run(root, "curl", ["-fsSL", url]));
    },
    npmResolves(url) {
      return spawnSync("curl", ["-fsSL", url], { cwd: root, encoding: "utf8" }).status === 0;
    },
  };
}

// Registry state for the release at `commit` (the tag's commit), with the plan
// read from that commit's blob. `lookup` and `npm` are injectable for tests.
export function remoteRegistries(root, commit, version, lookup = liveLookup(root)) {
  if (!/^[0-9a-f]{40}$/.test(commit)) fail(`release commit is not a full sha: ${commit}`);
  const { plan } = readReleasePlanAt(root, commit, version);
  checkRemote(remoteRequirements(root, commit, version), version, lookup);

  const npmNames = ["@3leaps/sysprims-darwin-arm64", "@3leaps/sysprims-linux-arm64-gnu", "@3leaps/sysprims-linux-arm64-musl", "@3leaps/sysprims-linux-x64-gnu", "@3leaps/sysprims-linux-x64-musl", "@3leaps/sysprims-win32-arm64-msvc", "@3leaps/sysprims-win32-x64-msvc", "@3leaps/sysprims"];
  const typescript = plan.surfaces.typescript;
  const npmVersion = typescript.disposition === "publish" ? version : typescript.retained_version;
  for (const name of npmNames) {
    const encoded = encodeURIComponent(name).replace("%2F", "%2f");
    const response = lookup.npm(`https://registry.npmjs.org/${encoded}/${npmVersion}`);
    if (response.version !== npmVersion || !response.dist?.integrity || !response.dist?.tarball) fail(`npm did not resolve complete metadata for ${name}@${npmVersion}`);
    // Exact: when gitHead is present it must name the tag's commit; when absent
    // (as with pre-packed tarballs), Sigstore provenance attestations must be
    // present so release-verify-registries.py binds the commit cryptographically.
    if (typescript.disposition === "publish") {
      if (response.gitHead !== undefined) {
        if (typeof response.gitHead !== "string" || !/^[0-9a-f]{40}$/.test(response.gitHead) || response.gitHead !== commit) {
          fail(`npm gitHead mismatch for ${name}@${npmVersion}`);
        }
      } else if (typeof response.dist?.attestations?.url !== "string" || !response.dist.attestations.url) {
        fail(`npm gitHead mismatch for ${name}@${npmVersion}`);
      }
    }
  }
  if (typescript.disposition === "skip") {
    const encoded = encodeURIComponent("@3leaps/sysprims").replace("%2F", "%2f");
    if (lookup.npmResolves(`https://registry.npmjs.org/${encoded}/${version}`)) fail(`skipped npm surface unexpectedly resolves at ${version}`);
  }
}

export function verifyPublishedStage(root, directory, version) {
  const anchorPath = `${directory}.anchor`;
  if (!existsSync(anchorPath) || lstatSync(anchorPath).isSymbolicLink() || !lstatSync(anchorPath).isFile()) {
    fail(`missing ${anchorPath}; stage the published release with make release-stage-published`);
  }
  const { files } = readFetchAnchor(root, directory, version);
  const { base, signed: inventory } = expectedInventory(version);
  assertInventory(directory, inventory, "published");
  const recorded = [...files.keys()].sort();
  if (JSON.stringify(recorded) !== JSON.stringify(base)) {
    fail(`published release anchor does not cover the exact base payload inventory; recorded=[${recorded.join(", ")}]`);
  }
  for (const name of base) {
    if (sha256(join(directory, name)) !== files.get(name)) {
      fail(`${name} differs from ${anchorPath}`);
    }
  }
  verifyTaggedAssets(root, directory, version);
  verifyChecksums(directory, base);
  run(root, "bash", ["scripts/verify-signatures.sh", directory]);
  run(root, "bash", ["scripts/verify-public-keys.sh", directory]);
}

function remote(root, directory, version) {
  refuseHiddenIndexEntries(root);
  verifyPublishedStage(root, directory, version);

  const platform = process.platform === "darwin"
    ? `darwin-${process.arch === "arm64" ? "arm64" : "amd64"}`
    : process.platform === "linux"
      ? `linux-${process.arch === "arm64" ? "arm64" : "amd64"}`
      : process.platform === "win32"
        ? `windows-${process.arch === "arm64" ? "arm64" : "amd64"}`
        : null;
  if (!platform) fail(`native remote smoke is unsupported on ${process.platform}`);
  const extension = process.platform === "win32" ? "zip" : "tar.gz";
  const asset = `sysprims-${version}-${platform}.${extension}`;
  const temporary = mkdtempSync(join(tmpdir(), "sysprims-native-smoke-"));
  try {
    const archivePath = join(directory, asset);
    if (extension === "zip") run(root, "unzip", ["-q", archivePath, "-d", join(temporary, "unpacked")]);
    else run(root, "tar", ["-xzf", archivePath, "-C", temporary]);
    const binaryName = process.platform === "win32" ? "sysprims.exe" : "sysprims";
    const located = run(root, "find", [temporary, "-type", "f", "-name", binaryName]).trim().split("\n").filter(Boolean);
    if (located.length !== 1) fail(`native smoke found ${located.length} ${binaryName} files`);
    const output = run(root, located[0], ["--version"]).trim();
    if (!output.includes(version)) fail(`native binary reports ${output}, expected ${version}`);
  } finally { rmSync(temporary, { recursive: true, force: true }); }
}

function isCiEnv() {
  for (const name of ["GITHUB_ACTIONS", "CI"]) {
    const val = (process.env[name] ?? "").trim().toLowerCase();
    if (val && val !== "0" && val !== "false") return true;
  }
  return false;
}

function publishRelease(root, directory, version, commit) {
  refuseHiddenIndexEntries(root);
  provenance(root, version, commit);
  uploaded(root, directory, version);
  const tag = `v${version}`;
  run(root, "gh", ["release", "edit", tag, "--repo", "3leaps/sysprims", "--draft=false"]);
  const publishedFixture = process.env.SYSPRIMS_PUBLISHED_RELEASE_METADATA_FILE;
  if (publishedFixture && isCiEnv()) {
    fail("SYSPRIMS_PUBLISHED_RELEASE_METADATA_FILE is not accepted under GitHub Actions or CI");
  }
  const published = publishedFixture
    ? JSON.parse(readFileSync(publishedFixture, "utf8"))
    : JSON.parse(run(root, "gh", ["api", `repos/3leaps/sysprims/releases/tags/${tag}`]));
  if (published.tag_name !== tag || published.draft !== false || published.immutable !== true) {
    fail(`published release ${tag} is not immutable (draft=${published.draft}, immutable=${published.immutable})`);
  }
  if (publishedFixture) {
    console.log(`[ok] verified immutable release metadata for ${tag} (fixture)`);
  }
}

function verifyRegistries(root, directory, version, commit) {
  refuseHiddenIndexEntries(root);
  verifyPublishedStage(root, directory, version);
  remoteRegistries(root, commit, version);
  const { plan } = readReleasePlanAt(root, commit, version);
  if (plan.surfaces.typescript?.disposition === "publish") {
    run(root, "python3", ["-I", "-B", "scripts/release-verify-registries.py", "--version", version, "--commit", commit]);
  }
}

function parseArguments(argv) {
  const command = argv[0];
  let root = defaultRoot;
  let directory = join(defaultRoot, "dist/release");
  for (let index = 1; index < argv.length; index += 1) {
    if (argv[index] === "--root") root = resolve(argv[++index]);
    else if (argv[index] === "--dir") directory = resolve(argv[++index]);
    else fail(`unknown argument: ${argv[index]}`);
  }
  return { command, root, directory };
}

function main() {
  const { command, root, directory } = parseArguments(process.argv.slice(2));
  const tagged = TAG_READING_COMMANDS.includes(command) ? taggedRelease(root) : null;
  const version = tagged ? tagged.version : readVersion(root);
  switch (command) {
    case "provenance": provenance(root, version); break;
    case "downloaded": downloaded(root, directory, version); break;
    case "checksummed": checksummed(root, directory, version); break;
    case "require-checksummed": requireChecksummed(root, directory, version); break;
    case "signed": signed(root, directory, version); break;
    case "uploaded": uploaded(root, directory, version); break;
    case "remote": remote(root, directory, version); break;
    case "publish": publishRelease(root, directory, version, tagged.commit); break;
    case "verify-registries": verifyRegistries(root, directory, version, tagged.commit); break;
    default: fail("usage: release-integrity.mjs <provenance|downloaded|checksummed|require-checksummed|signed|uploaded|remote|publish|verify-registries> [--root PATH] [--dir PATH]");
  }
  console.log(`[ok] release ${command} guard passed for v${version}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); }
  catch (error) { console.error(`[ERROR] ${error.message}`); process.exitCode = 1; }
}
