test("phase inventory and checksum manifests reject leftovers and wrong hashes", () => {
  const root = mkdtempSync(join(tmpdir(), "sysprims-inventory-test-")); roots.push(root);
  const { base } = expectedInventory("0.2.3");
  for (const name of base) writeFileSync(join(root, name), `${name}\n`);
  const manifest = (algorithm) => base.map((name) => `${hash(Buffer.from(`${name}\n`), algorithm)}  ${name}`).join("\n") + "\n";
  writeFileSync(join(root, "SHA256SUMS"), manifest("sha256"));
  writeFileSync(join(root, "SHA512SUMS"), manifest("sha512"));
  assert.doesNotThrow(() => verifyChecksums(root, base));
  assert.doesNotThrow(() => assertInventory(root, [...base, "SHA256SUMS", "SHA512SUMS"].sort(), "checksummed"));
  writeFileSync(join(root, "leftover-v9.9.9.zip"), "foreign\n");
  assert.throws(() => assertInventory(root, [...base, "SHA256SUMS", "SHA512SUMS"].sort(), "checksummed"), /extra=.*leftover/);
  rmSync(join(root, "leftover-v9.9.9.zip"));
  writeFileSync(join(root, base[0]), "changed\n");
  assert.throws(() => verifyChecksums(root, base), /digest mismatch/);
});

