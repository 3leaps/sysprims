#!/usr/bin/env python3
"""Prepare the per-tag annotation messages outside the repository, never clobbering.

One file per release tag in SYSPRIMS_TAG_MESSAGE_DIR, named after the tag with
"/" replaced by "__" and a ".txt" suffix. A new file holds the required subject
and placeholders; the maintainer completes it, and `--validate-message` (used by
the tag scripts) refuses a file that still has a placeholder or no footer.
"""

import json
import os
import re
import sys
from pathlib import Path

FOOTER = re.compile(
    r"(?:^|\n)Generated by .+ via .+ under supervision of @3leapsdave\n\n"
    r"Co-Authored-By: .+ <noreply@3leaps\.net>\n"
    r"Role: [a-z][a-z0-9-]*\n"
    r"Committer-of-Record: @3leapsdave\n$"
)
PLACEHOLDER = re.compile(r"<(?:[A-Z][A-Z -]*|model|interface[^<>]*|role)>")


def fail(reason: str) -> None:
    raise ValueError(reason)


def subject_for(tag: str, version: str) -> str:
    return f"Release {version}" if tag == f"v{version}" else tag


def validate_message(data: bytes, subject: str | None = None) -> str:
    try:
        message = data.decode("utf-8")
    except UnicodeError:
        fail("tag message must be UTF-8")
    if (
        not data
        or b"\x00" in data
        or b"\r" in data
        or not data.endswith(b"\n")
        or data.endswith(b"\n\n")
        or any(line.rstrip(b" \t") != line for line in data.splitlines())
    ):
        fail(
            "tag message needs one final newline and no CR, NUL or trailing whitespace"
        )
    if PLACEHOLDER.search(message):
        fail("tag message still contains a placeholder")
    if not FOOTER.search(message):
        fail("tag message must end with the complete attribution footer")
    if subject is not None and message.split("\n", 1)[0] != subject:
        fail(f"tag message subject must be {subject!r}")
    return message


def tag_set(root: Path, version: str) -> list[str]:
    plan = json.loads((root / f"docs/releases/v{version}.json").read_text())
    tags = []
    for prefix in (root / "config/release/release-tags.txt").read_text().split():
        if (
            prefix == "bindings/go/sysprims/v"
            and plan["surfaces"]["go"]["disposition"] != "publish"
        ):
            continue
        if (
            prefix == "go/recurrence/v"
            and not (root / "go/recurrence/go.mod").is_file()
        ):
            continue
        if prefix not in ("v", "bindings/go/sysprims/v", "go/recurrence/v"):
            fail(f"unknown tag prefix {prefix!r}")
        tags.append(f"{prefix}{version}")
    return tags


def message_dir(root: Path, tag: str) -> Path:
    raw = os.environ.get("SYSPRIMS_TAG_MESSAGE_DIR", "")
    directory = Path(raw)
    if (
        not raw
        or not directory.is_absolute()
        or ".." in directory.parts
        or directory.name != tag
    ):
        fail(
            "SYSPRIMS_TAG_MESSAGE_DIR must be an absolute directory ending in the release tag"
        )
    current = Path(directory.anchor)
    for part in directory.parts[1:]:
        current /= part
        if current.is_symlink():
            fail("SYSPRIMS_TAG_MESSAGE_DIR may not have symlink ancestors")
    resolved = directory.resolve(strict=False)
    if resolved == root or root in resolved.parents:
        fail("SYSPRIMS_TAG_MESSAGE_DIR must be outside the repository")
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    if directory.is_symlink() or not directory.is_dir():
        fail("SYSPRIMS_TAG_MESSAGE_DIR must be a real directory")
    return directory


def prepare() -> None:
    root = Path(__file__).resolve().parent.parent
    version = (root / "VERSION").read_text().strip()
    release_tag = os.environ.get("SYSPRIMS_RELEASE_TAG", "")
    if release_tag != f"v{version}":
        fail("SYSPRIMS_RELEASE_TAG must match VERSION")
    directory = message_dir(root, release_tag)
    for tag in tag_set(root, version):
        file = directory / f"{tag.replace('/', '__')}.txt"
        skeleton = (
            f"{subject_for(tag, version)}\n\n"
            "<SUMMARY OF THE RELEASE>\n\n"
            "Generated by <model> via <interface> under supervision of @3leapsdave\n\n"
            "Co-Authored-By: <model> <noreply@3leaps.net>\n"
            "Role: <role>\n"
            "Committer-of-Record: @3leapsdave\n"
        ).encode()
        try:
            descriptor = os.open(
                file, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600
            )
        except FileExistsError:
            state = "preserved"
        else:
            with os.fdopen(descriptor, "wb") as output:
                output.write(skeleton)
            state = "created"
        if file.is_symlink() or not file.is_file():
            fail(f"{file.name} must be a regular file")
        try:
            validate_message(file.read_bytes(), subject_for(tag, version))
            status = "complete"
        except ValueError as error:
            status = f"incomplete: {error}"
        print(
            f"[{'ok' if status == 'complete' else '..'}] {state} {file.name} ({status})"
        )


def main() -> None:
    args = sys.argv[1:]
    if len(args) in (2, 3) and args[0] == "--validate-message":
        subject = args[2] if len(args) == 3 else None
        validate_message(Path(args[1]).read_bytes(), subject)
    elif not args:
        prepare()
    else:
        fail(
            "usage: release-prepare-tag-message.py [--validate-message FILE [SUBJECT]]"
        )


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
        detail = (
            str(error)
            if isinstance(error, ValueError)
            else "unable to prepare tag messages"
        )
        print(f"error: {detail}", file=sys.stderr)
        sys.exit(1)
